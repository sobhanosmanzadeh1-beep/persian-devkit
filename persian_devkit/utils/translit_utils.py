"""تبدیل فارسی ↔ فینگلیش (لاتین‌نویسی)."""
from __future__ import annotations

import re

#فارسی → فینگلیش
_FA_TO_LATIN: dict[str, str] = {
    "آ": "a", "ا": "a", "ب": "b", "پ": "p", "ت": "t", "ث": "s",
    "ج": "j", "چ": "ch", "ح": "h", "خ": "kh", "د": "d", "ذ": "z",
    "ر": "r", "ز": "z", "ژ": "zh", "س": "s", "ش": "sh", "ص": "s",
    "ض": "z", "ط": "t", "ظ": "z", "ع": "a", "غ": "gh", "ف": "f",
    "ق": "gh", "ک": "k", "ك": "k", "گ": "g", "ل": "l", "م": "m",
    "ن": "n", "و": "v", "ه": "h", "ی": "y", "ي": "y", "ء": "",
    "أ": "a", "إ": "e", "ؤ": "o", "ئ": "y", "\u200c": "-",
    "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
    "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
}

#فینگلیش → فارسی
# ترتیب مهم است (چند-حرفی قبل از تک-حرفی)
_LATIN_TO_FA: list[tuple[str, str]] = [
    ("kh", "خ"), ("ch", "چ"), ("sh", "ش"), ("zh", "ژ"), ("gh", "ق"),
    ("aa", "آ"), ("ee", "ی"), ("oo", "و"), ("ou", "و"),
    ("a", "ا"), ("b", "ب"), ("c", "ک"), ("d", "د"), ("e", "ِ"),
    ("f", "ف"), ("g", "گ"), ("h", "ه"), ("i", "ی"), ("j", "ج"),
    ("k", "ک"), ("l", "ل"), ("m", "م"), ("n", "ن"), ("o", "و"),
    ("p", "پ"), ("q", "ق"), ("r", "ر"), ("s", "س"), ("t", "ت"),
    ("u", "و"), ("v", "و"), ("w", "و"), ("x", "کس"), ("y", "ی"),
    ("z", "ز"),
]


def to_finglish(text: str) -> str:
    """تبدیل متن فارسی به فینگلیش (لاتین).

    مثال: «سلام دنیا» → «salam donya»
    """
    result = []
    for ch in text:
        if ch in _FA_TO_LATIN:
            result.append(_FA_TO_LATIN[ch])
        elif ch.isspace():
            result.append(" ")
        else:
            result.append(ch)
    # پاک‌سازی فاصله‌های اضافی
    return re.sub(r"\s+", " ", "".join(result)).strip()


def to_persian(text: str) -> str:
    """تبدیل فینگلیش به فارسی (تقریبی).

    مثال: «salam» → «سالام»
    توجه: این تبدیل دقیق نیست و به متن وابسته است.
    """
    result = text.lower()
    for latin, fa in _LATIN_TO_FA:
        result = result.replace(latin, fa)
    return result
